class Interview(db.Model):
    __tablename__ = 'interviews'

    id = db.Column(db.Integer, primary_key=True)
    job_id = db.Column(db.Integer, db.ForeignKey('jobs.id'), nullable=True)
    # Nullable: an interview not tied to a job (job_id is None) can't be tied to
    # one of that job's stages either. stage_name stays the source of truth for
    # display and for ad-hoc interviews with no template; this FK is the real
    # link back to the template when there is one, instead of matching by name.
    meeting_stage_template_id = db.Column(
        db.Integer, db.ForeignKey('meeting_stage_templates.id'), nullable=True
    )
    stage_name = db.Column(db.String(100), nullable=False)  # e.g. Orientation, Technical Interview, Onsite
    meeting_type = db.Column(db.String(50), nullable=False)  # Interview, Orientation, or Other
    location = db.Column(db.String(255))  # room, address, or meeting link
    scheduled_start = db.Column(db.DateTime, nullable=False)
    scheduled_end = db.Column(db.DateTime, nullable=False)
    capacity = db.Column(db.Integer, default=1, nullable=False)
    # The three columns below are only populated for an interview booked
    # through the public apply flow (routes/apply.py) - null for anything a
    # recruiter creates directly (manual sessions, ad-hoc interviews).
    # 9-char human-typeable code a candidate uses on the public status-lookup
    # page (see models.generate_confirmation_code) instead of needing an
    # account/login.
    confirmation_code = db.Column(db.String(9), unique=True, index=True, nullable=True)
    # The Microsoft Teams meeting link from the created calendar event's
    # onlineMeeting.joinUrl - duplicated here (rather than only ever
    # re-fetched from Microsoft) so the status page and confirmation email
    # can display it without another API call.
    meeting_link = db.Column(db.String(500), nullable=True)
    # Calendar event id backing this interview, so it can later be
    # updated/cancelled on the calendar provider's side (e.g. if a recruiter
    # cancels the interview in-app) - not exposed via to_dict, internal
    # bookkeeping only.
    calendar_event_id = db.Column(db.String(255), nullable=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    VALID_MEETING_TYPES = ('Interview', 'Orientation', 'Other')

    job = db.relationship('Job', backref='interviews')
    meeting_stage_template = db.relationship('MeetingStageTemplate')
    candidates = db.relationship('Candidate', secondary=interview_candidates, backref='interviews')

    def to_dict(self):
        return {
            "id": self.id,
            "job_id": self.job_id,
            "job_title": self.job.title if self.job else None,
            "meeting_stage_template_id": self.meeting_stage_template_id,
            "stage_name": self.stage_name,
            "meeting_type": self.meeting_type,
            "location": self.location,
            "scheduled_start": iso_utc(self.scheduled_start),
            "scheduled_end": iso_utc(self.scheduled_end),
            "capacity": self.capacity,
            "scheduled_count": len(self.candidates),
            "candidates": [{"id": c.id, "name": c.display_name} for c in self.candidates],
            "confirmation_code": self.confirmation_code,
            "meeting_link": self.meeting_link,
            "created_at": iso_utc(self.created_at)
        }


class Candidate(db.Model):
    __tablename__ = 'candidates'

    id = db.Column(db.Integer, primary_key=True)
    name = db.Column(db.String(120), nullable=False)
    email = db.Column(db.String(120), nullable=False)
    phone = db.Column(db.String(20))
    job_id = db.Column(db.Integer, db.ForeignKey('jobs.id'), nullable=True)
    stage = db.Column(db.String(50), default='Applied')  # e.g. Applied, Interview, Offer, Hired, Rejected
    status = db.Column(db.String(50), default='Active')
    interviewer = db.Column(db.String(120))
    scheduled = db.Column(db.Boolean, default=False)
    city = db.Column(db.String(120))
    state = db.Column(db.String(60))
    # Street address - only collected via the public apply flow today
    # (routes/apply.py); candidates added by hand have this null, same as
    # resume below.
    address_line1 = db.Column(db.String(255))
    postal_code = db.Column(db.String(20))
    source = db.Column(db.String(120))  # e.g. Indeed, Referral
    resume_original_filename = db.Column(db.String(255))
    resume_stored_filename = db.Column(db.String(255))
    # Answers to the public apply flow's two fixed work-eligibility
    # questions (routes/apply.py) - null for candidates who didn't come
    # through that flow. Deliberately informational only: neither one blocks
    # submission or auto-disqualifies a candidate; a recruiter reviews them
    # like anything else on the candidate's profile.
    work_authorized = db.Column(db.Boolean, nullable=True)
    requires_visa_sponsorship = db.Column(db.Boolean, nullable=True)
    # The public apply flow's link back to this candidate's prescreen +
    # scheduling page (routes/apply.py) - null for candidates added by hand
    # instead. 64 hex chars from
    # models.generate_application_token; expires_at bounds how long that link
    # stays live, both to fail closed on a stale email and so dedupe (same
    # email+job re-applying) knows whether the existing row is still "live".
    application_token = db.Column(db.String(64), unique=True, index=True, nullable=True)
    application_token_expires_at = db.Column(db.DateTime, nullable=True)
    # Set the moment this candidate becomes disqualified - either
    # automatically, by the public apply flow evaluating their screening
    # answers (routes/apply.py's apply()), or manually, by a recruiter
    # setting a stage's status to 'Rejected' after an interview (routes/
    # candidates.py's update_stage_progress). Null for everyone else
    # (qualified, still-pending, or not through either path at all). Paired
    # with rejection_email_sent_at (also null until sent) so
    # scheduled_jobs.send_due_rejection_emails can find "disqualified more
    # than REJECTION_EMAIL_DELAY_MINUTES ago, not yet notified" without a
    # separate status enum. stage is set to 'Rejected' immediately (visible
    # to recruiters right away) independent of when the email actually goes
    # out.
    disqualified_at = db.Column(db.DateTime, nullable=True)
    rejection_email_sent_at = db.Column(db.DateTime, nullable=True)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    VALID_STAGES = ('Applied', 'Interview', 'Offer', 'Hired', 'Rejected')

    screening_answers = db.relationship(
        'CandidateScreeningAnswer', backref='candidate', cascade='all, delete-orphan', lazy=True
    )
    stage_progress = db.relationship(
        'CandidateStageProgress', backref='candidate', cascade='all, delete-orphan', lazy=True
    )
    documents = db.relationship(
        'CandidateDocument', backref='candidate', cascade='all, delete-orphan', lazy=True
    )

    @property
    def location(self):
        return ", ".join(filter(None, [self.city, self.state])) or None

    # Kept as properties (not just reading .name/.email/.phone directly)
    # since to_dict/to_detail_dict/Interview.to_dict's enrolled-candidate
    # list all go through these rather than the raw columns - a holdover
    # from when a candidate could be linked to their own self-registered
    # account (CandidateAccount) and these read live from there instead.
    # That concept was removed - candidates never get their own login; see
    # ApplicationStatusPage/routes/status.py for the phone/code-based
    # alternative - so these are direct passthroughs now, but keeping the
    # properties means nothing that already calls display_name/etc. needed
    # to change.
    @property
    def display_name(self):
        return self.name

    @property
    def display_email(self):
        return self.email

    @property
    def display_phone(self):
        return self.phone

    def to_dict(self):
        return {
            "id": self.id,
            "name": self.display_name,
            "email": self.display_email,
            "phone": self.display_phone,
            "job_id": self.job_id,
            "job_title": self.job.title if self.job else None,
            "stage": self.stage,
            "status": self.status,
            "interviewer": self.interviewer,
            "scheduled": self.scheduled,
            "city": self.city,
            "state": self.state,
            "address_line1": self.address_line1,
            "postal_code": self.postal_code,
            "location": self.location,
            "source": self.source,
            "has_resume": self.resume_stored_filename is not None,
            "resume_filename": self.resume_original_filename,
            "work_authorized": self.work_authorized,
            "requires_visa_sponsorship": self.requires_visa_sponsorship,
            "created_at": iso_utc(self.created_at),
            "updated_at": iso_utc(self.updated_at or self.created_at),
            "current_stage": self._current_stage_summary(),
        }

    def _current_stage_summary(self):
        """The stage progress row to surface on the candidates list: the
        soonest upcoming one, else the most recently touched one."""
        if not self.stage_progress:
            return None
        upcoming = [p for p in self.stage_progress if p.status == 'Upcoming' and p.scheduled_at]
        if upcoming:
            progress = min(upcoming, key=lambda p: p.scheduled_at)
        else:
            progress = max(self.stage_progress, key=lambda p: p.updated_at or p.id)
        return {
            "meeting_stage_template_id": progress.meeting_stage_template_id,
            "stage_name": progress.meeting_stage_template.stage_name
            if progress.meeting_stage_template
            else None,
            "status": progress.status,
            "scheduled_at": iso_utc(progress.scheduled_at),
        }

    def to_detail_dict(self):
        data = self.to_dict()
        # Job.screening_questions is already ordered (by stage, then question
        # sort_order) — re-sorting by question sort_order alone would scramble
        # that, since sort_order only orders questions within their own stage.
        questions = self.job.screening_questions if self.job else []
        answers_by_question = {a.question_id: a.answer_text for a in self.screening_answers}
        progress_by_template = {p.meeting_stage_template_id: p for p in self.stage_progress}
        templates = (
            sorted(self.job.meeting_stage_templates, key=lambda t: (t.sort_order, t.id))
            if self.job
            else []
        )

        data.update(
            {
                "screening_answers": [
                    {
                        "question_id": q.id,
                        "question_text": q.question_text,
                        "answer_options": q.answer_options or [],
                        # Lets the recruiter UI show whether the given answer
                        # actually qualifies the candidate (see
                        # routes/apply.py's _is_qualifying_answer, which
                        # applies this same rule automatically for the
                        # public apply flow) rather than just whether it was
                        # answered at all.
                        "qualified_answers": q.qualified_answers or [],
                        "answer_text": answers_by_question.get(q.id),
                    }
                    for q in questions
                ],
                "stages": [
                    {
                        "meeting_stage_template_id": t.id,
                        "stage_name": t.stage_name,
                        "meeting_type": t.meeting_type,
                        # Whether this stage can be booked via a real calendar
                        # (routes/candidates.py's get_available_slots/
                        # book_stage_slot) - lets the frontend show the live
                        # availability picker instead of a plain date/time
                        # field for a stage set up that way (interview stages
                        # always have been; orientation optionally can be too).
                        "interviewer_user_id": t.interviewer_user_id,
                        "duration_minutes": t.duration_minutes,
                        **(
                            progress_by_template[t.id].to_dict()
                            if t.id in progress_by_template
                            else {
                                "id": None,
                                "status": 'Upcoming',
                                "scheduled_at": None,
                                "location": None,
                                "notes": None,
                                "score_communication": None,
                                "score_energy": None,
                                "score_relevant_experience": None,
                                "cancellation_reason": None,
                                "prompt_reschedule": None,
                                "has_recording": False,
                                "recording_filename": None,
                            }
                        ),
                    }
                    for t in templates
                ],
                "documents": {d.onboarding_item_id: d.to_dict() for d in self.documents},
            }
        )
        return data


