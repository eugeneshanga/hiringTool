class CandidateStageProgress(db.Model):
    """A candidate's progress through one of their job's meeting stages:
    scheduling, status, interviewer notes, and scorecard ratings."""
    __tablename__ = 'candidate_stage_progress'

    id = db.Column(db.Integer, primary_key=True)
    candidate_id = db.Column(db.Integer, db.ForeignKey('candidates.id'), nullable=False)
    meeting_stage_template_id = db.Column(
        db.Integer, db.ForeignKey('meeting_stage_templates.id'), nullable=False
    )
    status = db.Column(db.String(30), default='Upcoming', nullable=False)
    scheduled_at = db.Column(db.DateTime)
    location = db.Column(db.String(255))
    notes = db.Column(db.Text)
    score_communication = db.Column(db.Integer)
    score_energy = db.Column(db.Integer)
    score_relevant_experience = db.Column(db.Integer)
    # Set together when a recruiter cancels via the "Cancel interview" modal.
    # Neither triggers any actual notification today - there's no email/SMS
    # infrastructure in this app yet, and no candidate-facing reschedule flow
    # for prompt_reschedule to hand off to - they're just recorded so the
    # recruiter's stated intent isn't lost.
    cancellation_reason = db.Column(db.Text)
    prompt_reschedule = db.Column(db.Boolean)
    # The uploaded recording of this stage's interview (see
    # routes/candidates.py's upload_recording/download_recording) - stored
    # the same way as Candidate.resume_stored_filename (file_storage.py, on
    # disk under UPLOAD_FOLDER, UUID-prefixed). One per (candidate, stage),
    # same as the rest of this row - a candidate with two virtual-interview
    # stages gets two independent recordings.
    recording_original_filename = db.Column(db.String(255))
    recording_stored_filename = db.Column(db.String(255))
    updated_at = db.Column(db.DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)

    # 'Upcoming' is set automatically by scheduling/rescheduling (routes/
    # candidates.py's book_stage_slot, routes/interviews.py's
    # enroll_candidate) - everything else here is a post-interview outcome a
    # recruiter sets by hand (or, for the two 'Yes' sub-states, the app
    # advances automatically - see routes/status.py's
    # _maybe_advance_to_information_received).
    #
    # The three 'Yes...' values are what gates the onboarding checklist on
    # the candidate's own status page (see routes/status.py's
    # _onboarding_checklist) - starts at 'Yes - Awaiting information' once a
    # recruiter records a positive outcome, then the app itself flips it to
    # 'Yes - Information received' once every required item for this stage
    # has a submission. Plain 'Yes' (no sub-state) also gates it, for a
    # stage that doesn't collect onboarding documents.
    #
    # 'No' mirrors the auto-disqualification path (screening answers) for a
    # candidate who doesn't work out at this stage, same as the "Cancel
    # interview" action - see routes/candidates.py's update_stage_progress,
    # which cascades it to Candidate.stage/disqualified_at too, not just
    # this row.
    VALID_STATUSES = (
        'Upcoming', 'Yes', 'Yes - Awaiting information', 'Yes - Information received',
        'No', 'Maybe', 'Hired', 'No show', 'No response', 'Needs review',
    )

    __table_args__ = (
        db.UniqueConstraint('candidate_id', 'meeting_stage_template_id', name='uq_candidate_stage'),
    )

    meeting_stage_template = db.relationship('MeetingStageTemplate')

    def to_dict(self):
        return {
            "id": self.id,
            "candidate_id": self.candidate_id,
            "meeting_stage_template_id": self.meeting_stage_template_id,
            "status": self.status,
            "scheduled_at": iso_utc(self.scheduled_at),
            "location": self.location,
            "notes": self.notes,
            "score_communication": self.score_communication,
            "score_energy": self.score_energy,
            "score_relevant_experience": self.score_relevant_experience,
            "cancellation_reason": self.cancellation_reason,
            "prompt_reschedule": self.prompt_reschedule,
            "has_recording": self.recording_stored_filename is not None,
            "recording_filename": self.recording_original_filename,
        }


